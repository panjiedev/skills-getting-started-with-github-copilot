def test_list_activities_returns_all_activity_data(client):
    # Arrange
    expected_activity_names = {
        "Chess Club",
        "Programming Class",
        "Gym Class",
        "Basketball",
        "Soccer",
        "Art Club",
        "Drama Club",
        "Robotics Club",
        "Debate Club",
    }

    # Act
    response = client.get("/activities")

    # Assert
    assert response.status_code == 200
    assert set(response.json()) == expected_activity_names
    assert response.json()["Chess Club"] == activities["Chess Club"]


